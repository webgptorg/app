#!/bin/bash
# Boots a Debian 13 cloud image with the relay host's real user data (NoCloud seed) under QEMU/KVM, places test
# secrets and a test relay image the way an admin and the deploy would, then checks the host from outside:
# verify.sh passes, a port scan shows 443 open to anyone and 22 only to the allowlist, the deploy key runs only its
# forced command, and a deliberately broken setting (password SSH) makes verify.sh fail.
#
# Needs root (bridge, tap, network namespace, NAT), Docker, qemu-system-x86, qemu-utils, cloud-image-utils, nmap and
# curl, and /dev/kvm: without it (a laptop's Linux VM on Apple silicon) QEMU emulates the CPU, which takes about ten
# times longer but boots the same image. Run from the repo root after `bun run --filter @ptbk/relay build`. Every
# secret is generated here for this run and thrown away with the VM.
set -euo pipefail

IMAGE_VERSION=20261017-2634
IMAGE_FILE=debian-13-genericcloud-amd64-$IMAGE_VERSION.qcow2
IMAGE_URL=https://cloud.debian.org/images/cloud/trixie/$IMAGE_VERSION/$IMAGE_FILE
IMAGE_SHA512=ec584ccabfef7120b4c4f7482adf0e615894d9292cedec446b64194b951ebe5dd97c336b5dcbae458333764b0edd516334506017f33c4f2020ef8d38b569ffe3
TOFU_IMAGE=ghcr.io/opentofu/opentofu:1.11.14@sha256:6913ba3b281b0b7d2c2cb286e3aaf64d48c8c113e692218066b1b308fa2a2c8a

BRIDGE=ptbk-br0
TAP=ptbk-tap0
OUTSIDER=ptbk-outsider
HOST_IP=10.231.0.1
VM_IP=10.231.0.10
OUTSIDER_IP=10.231.0.20
RELAY_HOSTNAME=relay-ci.relays.ptbk.test

repo=$(pwd)
work=${VM_TEST_WORK:-$(mktemp -d)}
mkdir -p "$work"

step() { printf '\n== %s\n' "$*"; }

cleanup() {
    status=$?
    if [[ -f $work/qemu.pid ]]; then kill "$(cat "$work/qemu.pid")" 2>/dev/null || true; fi
    if ((status != 0)) && [[ -f $work/console.log ]]; then
        echo "-- last lines of the VM console"
        tail -n 100 "$work/console.log"
    fi
    ip netns delete "$OUTSIDER" 2>/dev/null || true
    ip link delete "$TAP" 2>/dev/null || true
    ip link delete "$BRIDGE" 2>/dev/null || true
    iptables -t nat -D POSTROUTING -s 10.231.0.0/24 ! -o "$BRIDGE" -j MASQUERADE 2>/dev/null || true
    iptables -D FORWARD -i "$BRIDGE" -j ACCEPT 2>/dev/null || true
    iptables -D FORWARD -o "$BRIDGE" -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT 2>/dev/null || true
    exit "$status"
}
trap cleanup EXIT

ssh_opts=(-i "$work/admin" -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null -o LogLevel=ERROR
    -o ConnectTimeout=5 -o BatchMode=yes)
# Commands are built here on purpose: every value in them is generated by this script.
# shellcheck disable=SC2029
vm() { ssh "${ssh_opts[@]}" "ci@$VM_IP" "$@"; }

step "network: bridge, tap, an outsider outside the SSH allowlist, NAT to the internet"
ip link add "$BRIDGE" type bridge
ip addr add "$HOST_IP/24" dev "$BRIDGE"
ip link set "$BRIDGE" up
ip tuntap add "$TAP" mode tap
ip link set "$TAP" master "$BRIDGE" up
ip netns add "$OUTSIDER"
ip link add ptbk-veth0 type veth peer name ptbk-veth1
ip link set ptbk-veth0 master "$BRIDGE" up
ip link set ptbk-veth1 netns "$OUTSIDER"
ip -n "$OUTSIDER" addr add "$OUTSIDER_IP/24" dev ptbk-veth1
ip -n "$OUTSIDER" link set ptbk-veth1 up
sysctl -q -w net.ipv4.ip_forward=1
iptables -t nat -A POSTROUTING -s 10.231.0.0/24 ! -o "$BRIDGE" -j MASQUERADE
# Docker's FORWARD policy is drop; the VM needs the internet for packages, time and DNSSEC.
iptables -I FORWARD -i "$BRIDGE" -j ACCEPT
iptables -I FORWARD -o "$BRIDGE" -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT

step "keys, user data and seed"
ssh-keygen -q -t ed25519 -N '' -C ci-admin -f "$work/admin"
ssh-keygen -q -t ed25519 -N '' -C ci-deploy -f "$work/deploy"
docker run --rm -e HOME=/tmp -v "$repo/infra:/infra" -v "$work:/work" -w /infra/relay/test/render "$TOFU_IMAGE" \
    init -no-color -backend=false -input=false >/dev/null
docker run --rm -e HOME=/tmp -v "$repo/infra:/infra" -v "$work:/work" -w /infra/relay/test/render "$TOFU_IMAGE" \
    apply -no-color -auto-approve -input=false -state=/work/render.tfstate \
    -var "admin_key=$(cat "$work/admin.pub")" -var "deploy_key=$(cat "$work/deploy.pub")" \
    -var "ssh_allowlist=[\"$HOST_IP/32\"]" >/dev/null
docker run --rm -e HOME=/tmp -v "$repo/infra:/infra" -v "$work:/work" -w /infra/relay/test/render "$TOFU_IMAGE" \
    output -no-color -state=/work/render.tfstate -raw user_data >"$work/user-data"
printf 'instance-id: ptbk-relay-ci\nlocal-hostname: relay-ci\n' >"$work/meta-data"
cat >"$work/network-config" <<EOF
version: 2
ethernets:
  primary:
    match:
      macaddress: "52:54:00:12:34:56"
    addresses: [$VM_IP/24]
    routes:
      - to: default
        via: $HOST_IP
    nameservers:
      addresses: [9.9.9.9]
EOF
cloud-localds --network-config="$work/network-config" "$work/seed.iso" "$work/user-data" "$work/meta-data"

step "Debian cloud image $IMAGE_VERSION"
curl -fsSL --retry 3 -o "$work/$IMAGE_FILE" "$IMAGE_URL"
echo "$IMAGE_SHA512  $work/$IMAGE_FILE" | sha512sum -c -
qemu-img create -q -f qcow2 -F qcow2 -b "$work/$IMAGE_FILE" "$work/disk.qcow2" 10G

if [[ -w /dev/kvm ]]; then
    accel=(-enable-kvm -cpu host)
    boot_timeout=1500
else
    echo "no /dev/kvm: emulating the CPU (TCG)"
    accel=(-accel tcg,thread=multi -cpu max)
    boot_timeout=7200
fi

step "boot"
qemu-system-x86_64 "${accel[@]}" -m 4096 -smp 2 -display none -daemonize -pidfile "$work/qemu.pid" \
    -serial "file:$work/console.log" -monitor none \
    -drive "file=$work/disk.qcow2,if=virtio" -drive "file=$work/seed.iso,if=virtio,format=raw,readonly=on" \
    -netdev "tap,id=net0,ifname=$TAP,script=no,downscript=no" -device virtio-net-pci,netdev=net0,mac=52:54:00:12:34:56

# cloud-init installs packages and may reboot once for a new kernel (package_reboot_if_required), so wait for it
# across the reboot.
deadline=$((SECONDS + boot_timeout))
status=""
until [[ $status == "done" || $status == "error" ]]; do
    if ((SECONDS > deadline)); then
        echo "cloud-init did not finish" >&2
        exit 1
    fi
    sleep 10
    status=$(vm 'sudo cloud-init status --wait >/dev/null 2>&1; sudo cloud-init status' 2>/dev/null |
        sed -n 's/^status: //p' || true)
done
vm 'sudo cloud-init status --long'
[[ $status == "done" ]]

step "secrets, placed as an admin would (README)"
openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:P-256 -nodes -days 2 -subj "/CN=$RELAY_HOSTNAME" \
    -addext "subjectAltName=DNS:$RELAY_HOSTNAME" -keyout "$work/tls.key" -out "$work/tls.crt" 2>/dev/null
printf 'ptbk_rt_%s\n' "$(openssl rand -base64 32 | tr '+/' '-_' | tr -d '=')" >"$work/registry-token"
printf 'ptbk_mt_%s\n' "$(openssl rand -base64 32 | tr '+/' '-_' | tr -d '=')" >"$work/metrics-token"
for credential in registry-token metrics-token tls.crt tls.key; do
    vm "sudo install -m 0600 -o root -g root /dev/stdin /etc/ptbk-relay/credentials/$credential" <"$work/$credential"
done

step "a relay image, deployed as I-03's deploy script will (by digest)"
# The VM is amd64 whatever the machine running this test is.
docker build --quiet --platform linux/amd64 --tag localhost/ptbk-relay:ci --file infra/relay/test/relay.Containerfile \
    apps/relay/dist
docker save localhost/ptbk-relay:ci | vm 'sudo podman load --quiet'
digest=$(vm "sudo podman image inspect --format '{{.Digest}}' localhost/ptbk-relay:ci")
vm "echo 'PTBK_RELAY_IMAGE=localhost/ptbk-relay@$digest' | sudo install -m 0644 /dev/stdin /etc/ptbk-relay/image.env"
vm 'sudo systemctl start ptbk-relay.service'
for _ in $(seq 30); do
    if curl -fsS --max-time 3 -k --resolve "$RELAY_HOSTNAME:443:$VM_IP" "https://$RELAY_HOSTNAME/healthz" >/dev/null; then
        break
    fi
    sleep 2
done
curl -fsS --max-time 3 -k --resolve "$RELAY_HOSTNAME:443:$VM_IP" "https://$RELAY_HOSTNAME/healthz"
echo

step "metrics: 401 without the token, the series with it (I-04)"
metrics_url="https://$RELAY_HOSTNAME/metrics"
status=$(curl -sS -o /dev/null -w '%{http_code}' --max-time 3 -k --resolve "$RELAY_HOSTNAME:443:$VM_IP" "$metrics_url")
test "$status" = 401
curl -fsS --max-time 3 -k --resolve "$RELAY_HOSTNAME:443:$VM_IP" \
    -H "Authorization: Bearer $(cat "$work/metrics-token")" "$metrics_url" | grep -q '^ptbk_relay_tunnels_active 0$'

step "verify.sh"
infra/relay/verify.sh "ci@$VM_IP" "${ssh_opts[@]}"

step "port scan from the allowlisted address: 22 and 443"
nmap -Pn -n -p- -T4 --max-retries 1 --open -oG "$work/scan-allowed" "$VM_IP" >/dev/null
open_allowed=$(grep -o '[0-9]*/open/tcp' "$work/scan-allowed" | cut -d/ -f1 | sort -n | xargs)
echo "open: $open_allowed"
test "$open_allowed" = "22 443"

step "port scan from outside the allowlist: 443 only"
ip netns exec "$OUTSIDER" nmap -Pn -n -p- -T4 --max-retries 1 --open -oG "$work/scan-outsider" "$VM_IP" >/dev/null
open_outsider=$(grep -o '[0-9]*/open/tcp' "$work/scan-outsider" | cut -d/ -f1 | sort -n | xargs)
echo "open: $open_outsider"
test "$open_outsider" = 443

step "the deploy key runs only its forced command"
deploy_output=$(ssh -i "$work/deploy" -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null -o LogLevel=ERROR \
    -o BatchMode=yes "ptbk-deploy@$VM_IP" 'id' 2>&1 || true)
echo "$deploy_output"
grep -q 'no deploy script is installed on this host yet' <<<"$deploy_output"

step "a broken setting fails verify.sh: password SSH enabled"
vm "echo 'PasswordAuthentication yes' | sudo install -m 0600 /dev/stdin /etc/ssh/sshd_config.d/00-broken.conf"
if infra/relay/verify.sh "ci@$VM_IP" "${ssh_opts[@]}" >"$work/verify-broken.log"; then
    cat "$work/verify-broken.log"
    echo "verify.sh passed with password SSH enabled" >&2
    exit 1
fi
grep 'FAIL' "$work/verify-broken.log"
grep -q 'FAIL  sshd: passwordauthentication no' "$work/verify-broken.log"
vm 'sudo rm /etc/ssh/sshd_config.d/00-broken.conf'

printf '\nThe relay host passed the VM test.\n'
