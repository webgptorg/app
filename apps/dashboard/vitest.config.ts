import { cloudflareTest, readD1Migrations } from '@cloudflare/vitest-pool-workers';
import react from '@vitejs/plugin-react';
import { defineConfig } from 'vitest/config';

const WORKERS_TESTS = ['src/**/*.workers.test.ts', 'src/adapters/db/**/*.test.ts'];

export default defineConfig(async () => {
    const migrations = await readD1Migrations('./migrations');
    return {
        test: {
            // v8 coverage needs node:inspector, which workerd lacks, so `test` measures the unit and client projects and
            // runs the workers project separately; the files only workerd executes are excluded below (AGENTS.md step 6).
            coverage: {
                provider: 'v8' as const,
                include: ['src/**/*.{ts,tsx}'],
                exclude: [
                    'src/**/*.test.{ts,tsx}',
                    'src/**/*.d.ts',
                    // Generated by `generate`.
                    'src/paraglide/**',
                    'src/client/routeTree.gen.ts',
                    // Run only in workerd: the D1 adapter and the migrations setup, covered by the workers project.
                    'src/adapters/db/**',
                    // DOM bootstrap (createRoot on #root); everything it renders is App, which the client tests cover.
                    'src/client/main.tsx',
                ],
                thresholds: {
                    lines: 90,
                    branches: 90,
                    // Permission and fail-closed code must stay covered on its own, not only on average.
                    'src/domain/**': { lines: 100, branches: 100 },
                    'src/app/config.ts': { lines: 100, branches: 100 },
                },
            },
            projects: [
                {
                    test: {
                        name: 'unit',
                        environment: 'node',
                        include: [
                            'src/{domain,app,adapters}/**/*.test.ts',
                            'scripts/**/*.test.ts',
                            'test/**/*.test.ts',
                        ],
                        exclude: WORKERS_TESTS,
                    },
                },
                {
                    // Runs the built Worker (`build` comes first in `test`), so headers and CSP are the production ones.
                    plugins: [cloudflareTest({ wrangler: { configPath: './dist/ptbk_dashboard/wrangler.json' } })],
                    test: {
                        name: 'workers',
                        include: WORKERS_TESTS,
                        setupFiles: ['./src/adapters/db/apply-test-migrations.ts'],
                        provide: { migrations },
                    },
                },
                {
                    plugins: [react()],
                    test: {
                        name: 'client',
                        environment: 'jsdom',
                        include: ['src/client/**/*.test.{ts,tsx}'],
                    },
                },
            ],
        },
    };
});
